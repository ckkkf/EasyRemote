#!/usr/bin/env node
// 从 docs/spec/error-codes.md 生成 Go 与 Rust 错误码常量。生成物禁止手改。
// 用法: node scripts/gen-errors.mjs [--check]
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const fmtGo = (content) => {
  const dir = mkdtempSync(join(tmpdir(), 'ergo-'));
  const f = join(dir, 'x.go');
  writeFileSync(f, content);
  execSync('gofmt -w ' + JSON.stringify(f));
  return readFileSync(f, 'utf8');
};

const DOC = 'docs/spec/error-codes.md';
const GO_OUT = 'server/internal/errcode/codes_gen.go';
const RS_OUT = 'core/crates/er-common/src/errors_gen.rs';

const doc = readFileSync(DOC, 'utf8');
const rows = [];
for (const line of doc.split('\n')) {
  const m = line.match(/^\|\s*(\d{6})\s*\|\s*([A-Z][A-Z0-9_]+)\s*\|/);
  if (m) rows.push({ code: Number(m[1]), name: m[2] });
}
if (rows.length === 0) { console.error('未解析到错误码'); process.exit(1); }
const seen = new Map();
for (const r of rows) if (!seen.has(r.code)) seen.set(r.code, r);
const list = [...seen.values()].sort((a, b) => a.code - b.code);

const camel = (snake) => snake.toLowerCase().split('_').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('');

const go =
'// Code generated by scripts/gen-errors.mjs; DO NOT EDIT.\n' +
'// 源: docs/spec/error-codes.md\n' +
'package errcode\n\n' +
'// 由文档生成的错误码常量。\nconst (\n' +
list.map((r) => '\t' + camel(r.name) + ' Code = ' + r.code).join('\n') +
'\n)\n\n' +
'// generatedNames 是 code → 常量名。\nvar generatedNames = map[Code]string{\n' +
list.map((r) => '\t' + r.code + ': "' + r.name + '",').join('\n') +
'\n}\n\n' +
'// generatedAll 按码值升序。\nvar generatedAll = []Entry{\n' +
list.map((r) => '\t{' + camel(r.name) + ', "' + r.name + '"},').join('\n') +
'\n}\n';

const rs =
'// Code generated by scripts/gen-errors.mjs; DO NOT EDIT.\n' +
'// 源: docs/spec/error-codes.md\n\n' +
'/// 6 位错误码的原始值。\npub type RawCode = u32;\n\n' +
'macro_rules! codes {\n' +
'    ($($ident:ident => $num:expr, $name:expr;)*) => {\n' +
'        $(pub const $ident: RawCode = $num;)*\n\n' +
'        /// 返回码对应的常量名；未注册返回 "UNKNOWN"。\n' +
'        pub fn name(code: RawCode) -> &\'static str {\n' +
'            match code { $($num => $name,)* _ => "UNKNOWN" }\n' +
'        }\n\n' +
'        /// 返回全部已注册的 (code, name)，按码值升序。\n' +
'        pub fn all() -> &\'static [(RawCode, &\'static str)] {\n' +
'            &[$(($num, $name),)*]\n' +
'        }\n' +
'    };\n' +
'}\n\n' +
'codes! {\n' +
list.map((r) => '    ' + r.name + ' => ' + r.code + ', "' + r.name + '";').join('\n') +
'\n}\n';

const outputs = [
  { path: GO_OUT, content: fmtGo(go) },
  { path: RS_OUT, content: rs },
];
const checking = process.argv.includes('--check');
let bad = 0;
for (const o of outputs) {
  if (checking) {
    let cur = '';
    try { cur = readFileSync(o.path, 'utf8'); } catch { cur = ''; }
    if (cur !== o.content) { console.error('✗ ' + o.path + ' 与文档不一致'); bad++; }
    else console.log('✓ ' + o.path);
  } else {
    writeFileSync(o.path, o.content);
    console.log('generated ' + o.path + ' (' + list.length + ' codes)');
  }
}
if (checking) {
  if (bad > 0) process.exit(1);
  console.log('✔ 三端错误码与文档一致');
}