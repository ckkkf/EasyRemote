#!/usr/bin/env node
// 版本一致性校验：一个项目的版本号散落在多处，发布前必须全部对齐。
//
// 用法:
//   node scripts/check-version.mjs                 # 打印各处版本并校验是否一致
//   node scripts/check-version.mjs --tag v1.2.3    # 校验 tag 与各处版本一致（CI 用）
//   node scripts/check-version.mjs --set 1.2.3     # 把各处版本统一改为 1.2.3，并打印建议的 tag
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const SOURCES = [
  {
    name: 'VERSION',
    file: 'VERSION',
    read: (text) => text.trim(),
    write: (v) => v + '\n',
  },
  {
    name: 'core/Cargo.toml (workspace.package.version)',
    file: 'core/Cargo.toml',
    re: /^version\s*=\s*"(?<v>[^"]+)"(?<rest>[^\n]*)$/m,
    group: 1,
    build: (ver, g) => 'version = "' + ver + '"' + (g.rest || ''),
  },
  {
    name: 'web-admin/package.json',
    file: 'web-admin/package.json',
    re: /^\s*"version"\s*:\s*"(?<v>[^"]+)"(?<rest>[^\n]*)$/m,
    group: 1,
    build: (ver, g) => '  "version": "' + ver + '"' + (g.rest || '').trimEnd(),
  },
  {
    name: 'client/pubspec.yaml',
    file: 'client/pubspec.yaml',
    re: /^version:\s*(?<v>[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?)(?<suffix>\+[0-9]+)?$/m,
    group: 1,
    build: (ver, g) => 'version: ' + ver + (g.suffix || ''),
  },
];

const SEMVER = /^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$/;

// 客户端显示的版本号：由本脚本生成，禁止手写。
// 历史事故：侧边栏硬编码 `v1.0.0`、设置页硬编码 `1.0.0`，跟 pubspec 里的真实版本完全脱节。
const DART_VERSION_FILE = 'client/lib/version_gen.dart';

function dartVersionSource(version) {
  return [
    '// Code generated by scripts/check-version.mjs; DO NOT EDIT.',
    '// 源: VERSION / client/pubspec.yaml（用 --set 统一后自动重写本文件）',
    '',
    "const String erAppVersion = '" + version + "';",
    '',
  ].join('\n');
}

function readDartVersion() {
  const abs = path.join(ROOT, DART_VERSION_FILE);
  if (!fs.existsSync(abs)) return { ok: false, reason: '文件不存在（跑 node scripts/check-version.mjs --set <版本> 生成）' };
  const m = fs.readFileSync(abs, 'utf8').match(/erAppVersion = '([^']+)'/);
  if (!m) return { ok: false, reason: '未找到 erAppVersion' };
  return { ok: true, value: m[1] };
}

function writeDartVersion(version) {
  const abs = path.join(ROOT, DART_VERSION_FILE);
  const next = dartVersionSource(version);
  if (fs.existsSync(abs) && fs.readFileSync(abs, 'utf8') === next) return 'unchanged';
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, next);
  return 'written';
}

function readVersion(src) {
  const abs = path.join(ROOT, src.file);
  if (!fs.existsSync(abs)) return { ok: false, reason: '文件不存在' };
  const text = fs.readFileSync(abs, 'utf8');
  // JSON 文件先保证语法合法，坏文件不能被当成"版本一致"
  if (src.file.endsWith('.json')) {
    try {
      JSON.parse(text);
    } catch (e) {
      return { ok: false, reason: 'JSON 语法错误: ' + e.message };
    }
  }
  if (src.read) return { ok: true, value: src.read(text) };
  const m = text.match(src.re);
  if (!m) return { ok: false, reason: '未找到版本字段' };
  return { ok: true, value: m[src.group] };
}

// 每处版本源的替换方式：用命名锚点重建整行，避免捕获组错位把数字粘到版本号后面。
// （历史事故：正则回调参数错位曾把 package.json 写成 "0.2.0"53，直接导致 npm ci 失败。）
function writeVersion(src, version) {
  const abs = path.join(ROOT, src.file);
  if (src.write) {
    fs.writeFileSync(abs, src.write(version));
    return 'written';
  }
  const text = fs.readFileSync(abs, 'utf8');
  if (!src.build) return 'failed';
  const m = text.match(src.re);
  if (!m) return 'failed';
  const next = text.slice(0, m.index) + src.build(version, m.groups || {}) + text.slice(m.index + m[0].length);
  if (next === text) return 'unchanged';
  fs.writeFileSync(abs, next);
  return 'written';
}

// 写回后必须还能被结构化解析，否则说明替换破坏了文件语法。
// 历史事故：正则回调参数错位曾把 package.json 写成 "0.2.0"53、Cargo.toml 写成 "0.2.0"285，
// 导致 npm ci 与 cargo metadata 双双失败——本地 tsc/go 都发现不了，只有 CI 才暴露。
function assertStillValid(file) {
  const abs = path.join(ROOT, file);
  const raw = fs.readFileSync(abs, 'utf8');
  if (file.endsWith('.json')) {
    JSON.parse(raw);
    return true;
  }
  if (file.endsWith('.toml')) {
    // 版本行必须是 键 = "纯语义化版本"，后面不能粘任何字符
    const line = raw.split('\n').find((l) => /^\s*version\s*=/.test(l));
    if (line && !/^\s*version\s*=\s*"[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?"\s*$/.test(line)) {
      throw new Error(file + ': 版本行格式异常 -> ' + line.trim());
    }
  }
  return true;
}

const args = process.argv.slice(2);
const tagIdx = args.indexOf('--tag');
const setIdx = args.indexOf('--set');

// ---------------------------------------------------------------- --set
if (setIdx !== -1) {
  const raw = (args[setIdx + 1] || '').replace(/^v/, '');
  if (!SEMVER.test(raw)) {
    console.error('用法: node scripts/check-version.mjs --set 1.2.3');
    process.exit(2);
  }
  if (!fs.existsSync(path.join(ROOT, 'VERSION'))) {
    fs.writeFileSync(path.join(ROOT, 'VERSION'), '0.0.0\n');
  }
  let writeFail = false;
  for (const s of SOURCES) {
    const res = writeVersion(s, raw);
    console.log((res === 'failed' ? '✗ ' : '✓ ') + s.name + ' -> ' + raw + (res === 'unchanged' ? '（已是该版本）' : ''));
    if (res === 'failed') writeFail = true;
    if (s.file.endsWith('.json') || s.file.endsWith('.toml')) {
      try {
        assertStillValid(s.file);
      } catch (e) {
        console.error('✗ 写回后文件语法损坏：' + e.message);
        writeFail = true;
      }
    }
  }
  if (writeFail) {
    console.error('');
    console.error('❌ 有版本源写入失败或损坏了文件，请检查后重试。');
    process.exit(1);
  }
  const dartRes = writeDartVersion(raw);
  console.log((dartRes === 'failed' ? '✗ ' : '✓ ') + DART_VERSION_FILE + ' -> ' + raw + (dartRes === 'unchanged' ? '（已是该版本）' : ''));
  if (dartRes === 'failed') writeFail = true;
  console.log('');
  console.log('版本已统一为 ' + raw + '。');
  console.log('下一步：bash scripts/gate.sh && git commit -am "chore(release): v' + raw + '"');
  console.log('打 Tag：git tag v' + raw + ' && git push origin v' + raw);
  process.exit(0);
}

// ---------------------------------------------------------------- 读取
const found = [];
let bad = false;
for (const s of SOURCES) {
  const r = readVersion(s);
  if (!r.ok) {
    console.log('✗ ' + s.name + ': ' + r.reason);
    bad = true;
    continue;
  }
  found.push({ name: s.name, value: r.value });
  console.log('  ' + s.name + ': ' + r.value);
}

{
  const r = readDartVersion();
  if (!r.ok) {
    console.log('✗ ' + DART_VERSION_FILE + ': ' + r.reason);
    bad = true;
  } else {
    found.push({ name: DART_VERSION_FILE, value: r.value });
    console.log('  ' + DART_VERSION_FILE + ': ' + r.value);
  }
}

const values = [...new Set(found.map((f) => f.value))];
let exitCode = bad ? 1 : 0;

if (values.length > 1) {
  console.error('');
  console.error('❌ 各处版本号不一致：' + values.join(' / '));
  console.error('   修复：node scripts/check-version.mjs --set <版本>');
  exitCode = 1;
} else if (values.length === 1 && !bad) {
  console.log('');
  console.log('✓ 各处版本一致：' + values[0]);
} else if (values.length === 1 && bad) {
  console.error('');
  console.error('❌ 有版本源读取失败（见上方 ✗ 项），无法确认版本一致');
}

// ---------------------------------------------------------------- --tag
if (tagIdx !== -1) {
  const tag = args[tagIdx + 1] || '';
  const tagVersion = tag.replace(/^v/, '');
  const current = values[0];
  if (!tag) {
    console.error('❌ --tag 需要一个参数，例如 --tag v1.0.0');
    exitCode = 2;
  } else if (tagVersion !== current) {
    console.error('❌ Tag ' + tag + ' 与包版本 ' + current + ' 不一致');
    console.error('   要么先升版本：node scripts/check-version.mjs --set ' + tagVersion);
    console.error('   要么改打 v' + current + ' 的 Tag。');
    exitCode = 1;
  } else {
    console.log('✓ Tag ' + tag + ' 与包版本一致');
  }
}

if (bad && exitCode === 0) exitCode = 1;
process.exit(exitCode);
