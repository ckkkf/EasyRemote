#!/usr/bin/env node
// 从 docs/spec/contract.yaml 生成三端契约（Go / TS / Dart）。生成物禁止手改。
// 用法: node scripts/gen-contract.mjs [--check]
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const SRC = 'docs/spec/contract.yaml';
const GO_OUT = 'server/internal/contract/types_gen.go';
const TS_OUT = 'web-admin/src/contract.ts';
const DART_OUT = 'client/lib/contract.dart';

const NL = String.fromCharCode(10);
const BT = String.fromCharCode(96);
const DQ = String.fromCharCode(34);

// ---------- 解析：只支持本项目用到的 YAML 子集（缩进映射 + key: value） ----------
function stripComment(s) {
  const i = s.indexOf(' #');
  return (i < 0 ? s : s.slice(0, i)).trim();
}

function parseYaml(src) {
  const out = {};
  let section = null;
  let name = null;
  for (const raw of src.split(NL)) {
    if (!raw.trim() || raw.trim().startsWith('#')) continue;
    const indent = raw.length - raw.trimStart().length;
    const line = raw.trim();
    const at = line.indexOf(':');
    if (at < 0) throw new Error('无法解析: ' + raw);
    const key = line.slice(0, at).trim();
    const val = stripComment(line.slice(at + 1));
    if (indent === 0) {
      section = key;
      out[section] = val ? val : {};
      name = null;
      continue;
    }
    if (indent === 2) {
      name = key;
      out[section][name] = val ? val : {};
      continue;
    }
    if (indent === 4) {
      if (!name) throw new Error('缺少上级键: ' + raw);
      out[section][name][key] = val;
      continue;
    }
    throw new Error('缩进过深: ' + raw);
  }
  return out;
}

function parseType(spec) {
  let s = String(spec).trim();
  let optional = false;
  if (s.endsWith('?')) {
    optional = true;
    s = s.slice(0, -1).trim();
  }
  const m = s.match(/^list<(.+)>$/);
  if (m) return { list: true, base: m[1].trim(), optional };
  const mm = s.match(/^map<(.+)>$/);
  if (mm) return { map: true, base: mm[1].trim(), optional };
  return { list: false, base: s, optional };
}

const ACR = { id: 'ID', ip: 'IP', ts: 'TS', url: 'URL', api: 'API', json: 'JSON', ok: 'OK' };
const camel = (s) =>
  s
    .split('_')
    .map((w) => ACR[w] || w.charAt(0).toUpperCase() + w.slice(1))
    .join('');
const lowerCamel = (s) => {
  const c = camel(s);
  return c.charAt(0).toLowerCase() + c.slice(1);
};
// Dart 保留字不能当标识符：契约里的 default / class 之类字段必须改名，JSON 键保持原样。
const DART_KEYWORDS = new Set([
  'abstract', 'as', 'assert', 'async', 'await', 'base', 'break', 'case', 'catch', 'class', 'const',
  'continue', 'covariant', 'default', 'deferred', 'do', 'dynamic', 'else', 'enum', 'export',
  'extends', 'extension', 'external', 'factory', 'false', 'final', 'finally', 'for', 'get', 'hide',
  'if', 'implements', 'import', 'in', 'interface', 'is', 'late', 'library', 'mixin', 'new', 'null',
  'of', 'on', 'operator', 'part', 'required', 'rethrow', 'return', 'sealed', 'set', 'show', 'static',
  'super', 'switch', 'sync', 'this', 'throw', 'true', 'try', 'type', 'typedef', 'var', 'void', 'when',
  'while', 'with', 'yield',
]);
const dartField = (s) => {
  const c = lowerCamel(s);
  return DART_KEYWORDS.has(c) ? c + 'Value' : c;
};
const errList = (e) =>
  (e.errors || '')
    .split(',')
    .map((x) => x.trim())
    .filter(Boolean);
const sortedEndpoints = (endpoints) =>
  Object.entries(endpoints).sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

// ---------- Go ----------
const GO_BASE = { string: 'string', int: 'int', bool: 'bool', time: 'time.Time', any: 'any', int64: 'int64' };
const goType = (spec) => {
  const p = parseType(spec);
  const base = GO_BASE[p.base] || p.base;
  // map<X> 表示「字符串键 → X」，与 JSON object 对齐。
  if (p.map) return 'map[string]' + base;
  return p.list ? '[]' + base : base;
};

function emitGo(types, endpoints) {
  const needsTime = Object.values(types).some((fields) =>
    Object.values(fields).some((t) => parseType(t).base === 'time'),
  );
  const L = [];
  L.push('// Code generated by scripts/gen-contract.mjs; DO NOT EDIT.');
  L.push('// 源: docs/spec/contract.yaml');
  L.push('package contract');
  L.push('');
  if (needsTime) L.push('import "time"', '');
  for (const [name, fields] of Object.entries(types)) {
    L.push('// ' + name + ' 的字段定义见 docs/spec/contract.yaml。');
    L.push('type ' + name + ' struct {');
    for (const [field, spec] of Object.entries(fields)) {
      const p = parseType(spec);
      const tag = BT + 'json:' + DQ + field + (p.optional ? ',omitempty' : '') + DQ + BT;
      L.push('  ' + camel(field) + ' ' + goType(spec) + ' ' + tag);
    }
    L.push('}', '');
  }
  L.push('// Endpoint 是一条接口的契约描述。');
  L.push('type Endpoint struct {');
  L.push('  ID       string');
  L.push('  Method   string');
  L.push('  Path     string');
  L.push('  Auth     string');
  L.push('  Response string');
  L.push('  Errors   []string');
  L.push('}', '');
  L.push('// Endpoints 是全部接口，按 ID 升序。');
  L.push('var Endpoints = []Endpoint{');
  for (const [id, e] of sortedEndpoints(endpoints)) {
    const errs = errList(e).map((x) => JSON.stringify(x)).join(', ');
    L.push(
      '  {ID: ' + JSON.stringify(id) + ', Method: ' + JSON.stringify(e.method) +
        ', Path: ' + JSON.stringify(e.path) + ', Auth: ' + JSON.stringify(e.auth || 'none') +
        ', Response: ' + JSON.stringify(e.response || '') + ', Errors: []string{' + errs + '}},',
    );
  }
  L.push('}');
  return L.join(NL) + NL;
}

// ---------- TypeScript ----------
const TS_BASE = { string: 'string', int: 'number', bool: 'boolean', time: 'string', any: 'unknown', int64: 'number' };
const tsType = (spec) => {
  const p = parseType(spec);
  const base = TS_BASE[p.base] || p.base;
  if (p.map) return 'Record<string, ' + base + '>';
  return p.list ? base + '[]' : base;
};

function emitTs(types, endpoints) {
  const L = [];
  L.push('// Code generated by scripts/gen-contract.mjs; DO NOT EDIT.');
  L.push('// 源: docs/spec/contract.yaml');
  L.push('');
  L.push('export type Envelope<T> = {');
  L.push('  code: number;');
  L.push('  name: string;');
  L.push('  data: T;');
  L.push('  trace_id: string;');
  L.push('};', '');
  L.push('export type ErrorEnvelope = {');
  L.push('  code: number;');
  L.push('  name: string;');
  L.push('  message: string;');
  L.push('  retryable: boolean;');
  L.push('  trace_id: string;');
  L.push('};', '');
  for (const [name, fields] of Object.entries(types)) {
    L.push('export type ' + name + ' = {');
    for (const [field, spec] of Object.entries(fields)) {
      const p = parseType(spec);
      L.push('  ' + field + (p.optional ? '?' : '') + ': ' + tsType(spec) + ';');
    }
    L.push('};', '');
  }
  L.push('export type EndpointSpec = {');
  L.push('  id: string;');
  L.push('  method: string;');
  L.push('  path: string;');
  L.push('  auth: string;');
  L.push('  response: string;');
  L.push('  errors: string[];');
  L.push('};', '');
  L.push('export const ENDPOINTS: readonly EndpointSpec[] = [');
  for (const [id, e] of sortedEndpoints(endpoints)) {
    const errs = errList(e).map((x) => "'" + x + "'").join(', ');
    L.push(
      "  { id: '" + id + "', method: '" + e.method + "', path: '" + e.path + "', auth: '" +
        (e.auth || 'none') + "', response: '" + (e.response || '') + "', errors: [" + errs + '] },',
    );
  }
  L.push('];');
  return L.join(NL) + NL;
}

// ---------- Dart ----------
const DART_BASE = { string: 'String', int: 'int', bool: 'bool', time: 'String', any: 'dynamic', int64: 'int' };
const dartType = (spec) => {
  const p = parseType(spec);
  const base = DART_BASE[p.base] || p.base;
  let t = base;
  if (p.map) t = 'Map<String, ' + base + '>';
  else if (p.list) t = 'List<' + base + '>';
  return p.optional ? t + '?' : t;
};

function emitDart(types, endpoints) {
  const L = [];
  L.push('// Code generated by scripts/gen-contract.mjs; DO NOT EDIT.');
  L.push('// 源: docs/spec/contract.yaml');
  L.push('');
  L.push('class Envelope<T> {');
  L.push('  const Envelope({required this.code, required this.name, required this.data, required this.traceId});');
  L.push('');
  L.push('  final int code;');
  L.push('  final String name;');
  L.push('  final T data;');
  L.push('  final String traceId;');
  L.push('');
  L.push('  bool get ok => code == 0;');
  L.push('}', '');
  for (const [name, fields] of Object.entries(types)) {
    L.push('class ' + name + ' {');
    L.push('  const ' + name + '({');
    for (const [field, spec] of Object.entries(fields)) {
      const p = parseType(spec);
      L.push('    ' + (p.optional ? '' : 'required ') + 'this.' + dartField(field) + ',');
    }
    L.push('  });', '');
    for (const [field, spec] of Object.entries(fields)) {
      L.push('  final ' + dartType(spec) + ' ' + dartField(field) + ';');
    }
    L.push('');
    L.push('  factory ' + name + '.fromJson(Map<String, dynamic> json) => ' + name + '(');
    for (const [field, spec] of Object.entries(fields)) {
      const p = parseType(spec);
      const base = DART_BASE[p.base] || p.base;
      const key = "'" + field + "'";
      let cast = 'json[' + key + ']';
      if (p.map) cast = 'Map<String, ' + base + '>.from(json[' + key + '] as Map? ?? const {})';
      else if (p.list) cast = '(json[' + key + '] as List<dynamic>? ?? const []).map((e) => e as ' + base + ').toList()';
      else if (base !== 'dynamic') cast = 'json[' + key + '] as ' + base + (p.optional ? '?' : '');
      L.push('    ' + dartField(field) + ': ' + cast + ',');
    }
    L.push('  );');
    L.push('}', '');
  }
  L.push('class EndpointSpec {');
  L.push('  const EndpointSpec({required this.id, required this.method, required this.path, required this.auth, required this.response, required this.errors});');
  L.push('');
  L.push('  final String id;');
  L.push('  final String method;');
  L.push('  final String path;');
  L.push('  final String auth;');
  L.push('  final String response;');
  L.push('  final List<String> errors;');
  L.push('}', '');
  L.push('const List<EndpointSpec> endpoints = <EndpointSpec>[');
  for (const [id, e] of sortedEndpoints(endpoints)) {
    const errs = errList(e).map((x) => "'" + x + "'").join(', ');
    L.push(
      "  EndpointSpec(id: '" + id + "', method: '" + e.method + "', path: '" + e.path + "', auth: '" +
        (e.auth || 'none') + "', response: '" + (e.response || '') + "', errors: <String>[" + errs + ']),',
    );
  }
  L.push('];');
  return L.join(NL) + NL;
}

// ---------- 主流程 ----------
function gofmt(content) {
  const dir = mkdtempSync(join(tmpdir(), 'ercontract-'));
  const f = join(dir, 'types_gen.go');
  writeFileSync(f, content);
  execSync('gofmt -w ' + JSON.stringify(f));
  return readFileSync(f, 'utf8');
}

const doc = parseYaml(readFileSync(SRC, 'utf8'));
const types = doc.types || {};
const endpoints = doc.endpoints || {};
if (Object.keys(types).length === 0) {
  console.error('未解析到 types，检查 ' + SRC);
  process.exit(1);
}

const outputs = [
  { path: GO_OUT, content: gofmt(emitGo(types, endpoints)) },
  { path: TS_OUT, content: emitTs(types, endpoints) },
  { path: DART_OUT, content: emitDart(types, endpoints) },
];

const check = process.argv.includes('--check');
let drift = false;
for (const o of outputs) {
  if (!check) {
    writeFileSync(o.path, o.content);
    console.log('✓ ' + o.path);
    continue;
  }
  let cur = '';
  try {
    cur = readFileSync(o.path, 'utf8');
  } catch {
    cur = '';
  }
  if (cur === o.content) continue;
  drift = true;
  const a = cur.split(NL);
  const b = o.content.split(NL);
  let i = 0;
  while (i < a.length && i < b.length && a[i] === b[i]) i++;
  console.error('✗ ' + o.path + ' 与契约不一致（首个差异行 ' + (i + 1) + '）');
  console.error('  磁盘: ' + JSON.stringify(a[i] === undefined ? '<缺失>' : a[i]));
  console.error('  期望: ' + JSON.stringify(b[i] === undefined ? '<缺失>' : b[i]));
}
if (check) {
  if (drift) {
    console.error('契约漂移：先改 docs/spec/contract.yaml 再跑 node scripts/gen-contract.mjs');
    process.exit(1);
  }
  console.log('✓ 三端契约一致（' + Object.keys(types).length + ' 个类型 / ' + Object.keys(endpoints).length + ' 条接口）');
}
