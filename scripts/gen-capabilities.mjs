#!/usr/bin/env node
// 从 docs/spec/capabilities.yaml 生成三端能力台账常量。生成物禁止手改。
// 用法: node scripts/gen-capabilities.mjs [--check]
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const SRC = 'docs/spec/capabilities.yaml';
const DART_OUT = 'client/lib/capability_gen.dart';
const GO_OUT = 'server/internal/capability/capability_gen.go';
const TS_OUT = 'web-admin/src/capability_gen.ts';

const MATURITIES = ['disabled', 'experimental', 'beta', 'stable'];
const FIELDS = ['title', 'maturity', 'owner', 'reason'];

// ---------- YAML 子集解析：只支持本文件用到的「缩进映射 + 标量」 ----------
function parse(src) {
  const caps = [];
  let inCaps = false;
  let cur = null;
  for (const raw of src.split('\n')) {
    if (!raw.trim() || raw.trim().startsWith('#')) continue;
    const indent = raw.length - raw.trimStart().length;
    const line = raw.trim();
    const at = line.indexOf(':');
    if (at < 0) throw new Error('无法解析: ' + raw);
    const key = line.slice(0, at).trim();
    const val = line.slice(at + 1).trim();
    if (indent === 0) {
      inCaps = key === 'capabilities';
      continue;
    }
    if (!inCaps) continue;
    if (indent === 2) {
      cur = { key, title: '', maturity: '', owner: '', reason: '' };
      caps.push(cur);
      continue;
    }
    if (indent === 4) {
      if (!cur) throw new Error('缺少能力键: ' + raw);
      if (!FIELDS.includes(key)) throw new Error('未知字段 ' + key + '（能力 ' + cur.key + '）');
      cur[key] = val;
      continue;
    }
    throw new Error('缩进不支持: ' + raw);
  }
  if (caps.length === 0) throw new Error('未解析到任何能力');
  const seen = new Set();
  for (const c of caps) {
    if (!/^[a-z][a-z0-9_]*$/.test(c.key)) throw new Error('能力 key 必须 snake_case: ' + c.key);
    if (seen.has(c.key)) throw new Error('能力 key 重复: ' + c.key);
    seen.add(c.key);
    for (const f of FIELDS) {
      if (!c[f]) throw new Error('能力 ' + c.key + ' 缺字段 ' + f);
    }
    if (!MATURITIES.includes(c.maturity)) {
      throw new Error('能力 ' + c.key + ' maturity 非法: ' + c.maturity);
    }
  }
  return caps;
}

const caps = parse(readFileSync(SRC, 'utf8'));
const q = (s) => JSON.stringify(s);
const camel = (m) => 'CapabilityMaturity.' + m;
const upper = (m) => 'Maturity' + m.charAt(0).toUpperCase() + m.slice(1);

const dart = '// Code generated by scripts/gen-capabilities.mjs; DO NOT EDIT.\n' +
  '// 源: docs/spec/capabilities.yaml\n\n' +
  '/// 能力成熟度。disabled 永不暴露；experimental 仅非发布构建。\n' +
  'enum CapabilityMaturity { disabled, experimental, beta, stable }\n\n' +
  '/// 一条能力台账记录（字段顺序与 YAML 一致）。\n' +
  'class CapabilitySpec {\n' +
  '  const CapabilitySpec({\n' +
  '    required this.key,\n' +
  '    required this.title,\n' +
  '    required this.maturity,\n' +
  '    required this.owner,\n' +
  '    required this.reason,\n' +
  '  });\n\n' +
  '  final String key;\n' +
  '  final String title;\n' +
  '  final CapabilityMaturity maturity;\n' +
  '  final String owner;\n' +
  '  final String reason;\n' +
  '}\n\n' +
  '/// 由 docs/spec/capabilities.yaml 生成；禁止手改。\n' +
  'const List<CapabilitySpec> kCapabilities = <CapabilitySpec>[\n' +
  caps.map((c) => '  CapabilitySpec(\n' +
    '    key: ' + q(c.key) + ',\n' +
    '    title: ' + q(c.title) + ',\n' +
    '    maturity: ' + camel(c.maturity) + ',\n' +
    '    owner: ' + q(c.owner) + ',\n' +
    '    reason: ' + q(c.reason) + ',\n' +
    '  ),').join('\n') +
  '\n];\n\n' +
  '/// 按 key 查台账；未登记返回 null（调用方必须按不可用处理）。\n' +
  'CapabilitySpec? capabilitySpecOf(String key) {\n' +
  '  for (final c in kCapabilities) {\n' +
  '    if (c.key == key) return c;\n' +
  '  }\n' +
  '  return null;\n' +
  '}\n';

const goBody = 'package capability\n\n' +
  '// Maturity 是能力成熟度。\n' +
  'type Maturity string\n\n' +
  '// 台账允许的成熟度取值；与 docs/spec/capabilities.yaml 的 generation 规则一致。\n' +
  'const (\n' +
  MATURITIES.map((m) => '\t' + upper(m) + ' Maturity = ' + q(m)).join('\n') +
  '\n)\n\n' +
  '// Spec 是一条能力台账记录。\n' +
  'type Spec struct {\n' +
  '\tKey      string\n' +
  '\tTitle    string\n' +
  '\tMaturity Maturity\n' +
  '\tOwner    string\n' +
  '\tReason   string\n' +
  '}\n\n' +
  '// generatedSpecs 由 docs/spec/capabilities.yaml 生成；顺序即展示顺序。\n' +
  'var generatedSpecs = []Spec{\n' +
  caps.map((c) => '\t{Key: ' + q(c.key) + ', Title: ' + q(c.title) + ', Maturity: ' + upper(c.maturity) +
    ', Owner: ' + q(c.owner) + ', Reason: ' + q(c.reason) + '},').join('\n') +
  '\n}\n';

const go = '// Code generated by scripts/gen-capabilities.mjs; DO NOT EDIT.\n' +
  '// 源: docs/spec/capabilities.yaml\n' + goBody;

const ts = '// Code generated by scripts/gen-capabilities.mjs; DO NOT EDIT.\n' +
  '// 源: docs/spec/capabilities.yaml\n\n' +
  'export type CapabilityMaturity = ' + MATURITIES.map((m) => q(m)).join(' | ') + ';\n\n' +
  'export interface CapabilitySpec {\n' +
  '  readonly key: string;\n' +
  '  readonly title: string;\n' +
  '  readonly maturity: CapabilityMaturity;\n' +
  '  readonly owner: string;\n' +
  '  readonly reason: string;\n' +
  '}\n\n' +
  'export const CAPABILITIES: readonly CapabilitySpec[] = [\n' +
  caps.map((c) => '  { key: ' + q(c.key) + ', title: ' + q(c.title) + ', maturity: ' + q(c.maturity) +
    ', owner: ' + q(c.owner) + ', reason: ' + q(c.reason) + ' },').join('\n') +
  '\n];\n';

const fmtGo = (content) => {
  const dir = mkdtempSync(join(tmpdir(), 'ergocap-'));
  const f = join(dir, 'x.go');
  writeFileSync(f, content);
  execSync('gofmt -w ' + JSON.stringify(f));
  return readFileSync(f, 'utf8');
};

const outputs = [
  { path: DART_OUT, content: dart },
  { path: GO_OUT, content: fmtGo(go) },
  { path: TS_OUT, content: ts },
];
const checking = process.argv.includes('--check');
let bad = 0;
for (const o of outputs) {
  if (checking) {
    let cur = '';
    try { cur = readFileSync(o.path, 'utf8'); } catch { cur = ''; }
    if (cur !== o.content) { console.error('✗ ' + o.path + ' 与台账不一致'); bad++; }
    else console.log('✓ ' + o.path);
  } else {
    writeFileSync(o.path, o.content);
    console.log('generated ' + o.path);
  }
}
if (checking) {
  if (bad > 0) process.exit(1);
  console.log('✔ 三端能力台账与 docs/spec/capabilities.yaml 一致');
}
